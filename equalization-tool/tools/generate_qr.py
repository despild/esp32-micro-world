"""Generate compact, offline QR bitmaps; verify the exact OLED pixels decode."""
from pathlib import Path
import json
import qrcode
import zxingcpp
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'output' / 'qr'
SKETCH = ROOT / 'firmware' / 'WebQrTest'
SSID, PASSWORD, URL = 'EQ-C3', 'eqtest32', 'http://192.168.4.1'

def main():
    OUT.mkdir(parents=True, exist_ok=True)
    header = ['// Generated by tools/generate_qr.py. Test network credentials only.', '#pragma once', '#include <stdint.h>',
              f'static const char WIFI_SSID[] = "{SSID}";', f'static const char WIFI_PASSWORD[] = "{PASSWORD}";']
    results = []
    for name, payload in [('WIFI', f'WIFI:T:WPA;S:{SSID};P:{PASSWORD};;'), ('URL', URL)]:
        qr = qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_L, border=4, box_size=1)
        qr.add_data(payload, optimize=0)
        qr.make(fit=True)
        matrix = qr.get_matrix()
        size = len(matrix)
        assert size <= 40, f'{name} exceeds panel height'
        x0, y0 = (40-size)//2, (40-size)//2
        oled = Image.new('L', (72, 40), 0)
        for y, row in enumerate(matrix):
            for x, dark in enumerate(row):
                oled.putpixel((x+x0, y+y0), 0 if dark else 255)
        decoded = zxingcpp.read_barcode(oled.resize((720, 400), Image.Resampling.NEAREST))
        assert decoded and decoded.text == payload, f'{name} failed QR decode'
        oled.save(OUT / f'{name.lower()}-oled-native.png')
        oled.resize((720, 400), Image.Resampling.NEAREST).save(OUT / f'{name.lower()}-oled.png')
        qr.make_image().resize((size*12, size*12), Image.Resampling.NEAREST).save(OUT / f'{name.lower()}-large.png')
        # Packed row-major bits: 1 means dark QR module, including white quiet zone.
        flat = [int(dark) for row in matrix for dark in row]
        data = [sum(flat[i+j] << (7-j) for j in range(min(8, len(flat)-i))) for i in range(0, len(flat), 8)]
        header += [f'static const uint8_t QR_{name}_SIZE = {size};', f'static const uint8_t QR_{name}[] = {{',
                   ','.join(f'0x{b:02x}' for b in data), '};']
        results.append({'name':name, 'payload':payload, 'version':qr.version, 'size_with_quiet_zone':size, 'decode':'PASS'})
    (SKETCH / 'qr_bitmaps.h').write_text('\n'.join(header)+'\n', encoding='utf-8')
    (OUT / 'verification.json').write_text(json.dumps(results, indent=2), encoding='utf-8')
    print(json.dumps(results, indent=2))

if __name__ == '__main__':
    main()
